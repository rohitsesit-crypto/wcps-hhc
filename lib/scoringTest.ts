import { ALL_QUESTIONS, BEHAVIOUR_QUESTION_IDS, QUESTION_ORDER, PERSEVERANCE_IDS, SELF_MASTERY_IDS, GROWTH_IDS } from './quizData';
import { classify, reportIndexFor, wcpsBand, type Answers } from './scoring';

export const WCPS_FORMULA = 'WCPS = 0.40B + 0.20C + 0.15F + 0.10R + 0.05W + 0.025A + 0.025T + 0.05E';
const clamp = (n: number) => Math.max(0, Math.min(100, n));
export const COMPONENTS = [
  { key: 'B', label: 'Behaviour', ids: BEHAVIOUR_QUESTION_IDS, weight: .40 },
  { key: 'C', label: 'Country Opportunity Index', ids: ['q22'], weight: .20 },
  { key: 'F', label: 'Financial base', ids: ['q24'], weight: .15 },
  { key: 'R', label: 'Career path', ids: ['q23'], weight: .10 },
  { key: 'W', label: 'Wealth route', ids: ['q25'], weight: .05 },
  { key: 'A', label: 'Age', ids: ['q21'], weight: .025 },
  { key: 'T', label: 'Target horizon', ids: ['q26'], weight: .025 },
  { key: 'E', label: 'Education / career stage', ids: ['q27'], weight: .05 },
];

/** Reject incomplete/invalid attempts instead of treating them as low scores. */
export function weightedBreakdown(answers: Answers) {
  const invalid = QUESTION_ORDER.filter(id => {
    const index = answers[id];
    return !Number.isInteger(index) || index < 0 || !ALL_QUESTIONS[id].options[index];
  });
  if (invalid.length) throw new Error(`Complete valid answers for: ${invalid.join(', ')}`);
  const marks = (id: string) => ALL_QUESTIONS[id].options[answers[id]].points;
  const sum = (ids: string[]) => ids.reduce((total, id) => total + marks(id), 0);
  const rows = COMPONENTS.map(component => {
    const raw = sum(component.ids);
    const normalized = component.key === 'C' ? raw : component.key === 'B'
      ? clamp((raw - 20) / 60 * 100) : clamp((raw - 1) / 3 * 100);
    const formula = component.key === 'C' ? `${raw} (COI lookup, used directly)`
      : component.key === 'B' ? `(${raw} - 20) / 60 × 100`
      : `(${raw} - 1) / 3 × 100`;
    return { ...component, raw, formula, normalized, contribution: normalized * component.weight };
  });
  const exactTotal = clamp(rows.reduce((total, row) => total + row.contribution, 0));
  const wcps = Math.round(exactTotal * 10) / 10;
  // Match the existing engine: band classification precedes one-decimal storage rounding.
  const band = wcpsBand(exactTotal);
  const dimensions = [
    { key: 'P', label: 'Perseverance & Action', ids: PERSEVERANCE_IDS },
    { key: 'S', label: 'Self-Mastery & Discipline', ids: SELF_MASTERY_IDS },
    { key: 'G', label: 'Growth & Inner Mindset', ids: GROWTH_IDS },
  ].map(d => {
    const questions = d.ids.map(id => ({ id, answer: ALL_QUESTIONS[id].options[answers[id]].text, optionNumber: answers[id] + 1, marks: marks(id) }));
    const raw = sum(d.ids);
    const minimum = d.ids.length;
    const maximum = minimum * 4;
    const score = clamp((raw - minimum) / (maximum - minimum) * 100);
    return { ...d, questions, minimum, maximum, raw, score, roundedScore: Math.round(score * 10) / 10,
      level: classify(score), marksSum: questions.map(q => q.marks).join(' + '),
      formula: `(${raw} - ${minimum}) / ${maximum - minimum} × 100` };
  });
  return { rows, exactTotal, wcps, display: Math.round(wcps), label: band.label, dimensions,
    reportNumber: reportIndexFor(dimensions[0].level, dimensions[1].level, dimensions[2].level) };
}

export function presetAnswers(mode: 'lowest' | 'highest' | 'first'): Answers {
  return Object.fromEntries(QUESTION_ORDER.map(id => {
    const options = ALL_QUESTIONS[id].options;
    const target = mode === 'lowest' ? Math.min(...options.map(o => o.points)) : Math.max(...options.map(o => o.points));
    return [id, mode === 'first' ? 0 : options.findIndex(o => o.points === target)];
  }));
}

/** Hand-calculated expectations, not values generated by the calculator under test. */
export function runScoringChecks() {
  const high = presetAnswers('highest');
  const low = presetAnswers('lowest');
  const changedCountry = { ...high, q22: ALL_QUESTIONS.q22.options.findIndex(o => o.text === 'Nigeria') };
  const checks: { name: string; expected: number | string | boolean; actual: number | string | boolean }[] = [
    { name: 'Highest-options WCPS reference', expected: 99.24, actual: weightedBreakdown(high).exactTotal },
    { name: 'Lowest-options WCPS reference', expected: 10.046666666666667, actual: weightedBreakdown(low).exactTotal },
    { name: 'Q22-only change WCPS reference', expected: 14.86, actual: weightedBreakdown(high).exactTotal - weightedBreakdown(changedCountry).exactTotal },
    { name: 'Highest profile selects report 27', expected: 27, actual: weightedBreakdown(high).reportNumber },
    { name: 'Lowest profile selects report 1', expected: 1, actual: weightedBreakdown(low).reportNumber },
    { name: 'Highest one-decimal score', expected: 99.2, actual: weightedBreakdown(high).wcps },
    { name: 'Band boundary 79.49', expected: 'Well Positioned', actual: wcpsBand(79.49).label },
    { name: 'Band boundary 79.50', expected: 'Strongly Positioned', actual: wcpsBand(79.5).label },
  ];
  const highDimensions = weightedBreakdown(high).dimensions;
  const lowDimensions = weightedBreakdown(low).dimensions;
  for (let i = 0; i < 3; i += 1) {
    checks.push({ name: `${highDimensions[i].key}: highest answers score 100`, expected: 100, actual: highDimensions[i].score });
    checks.push({ name: `${lowDimensions[i].key}: lowest answers`, expected: i === 1 ? 100 / 12 : 0, actual: lowDimensions[i].score });
    checks.push({ name: `${highDimensions[i].key}: changing Q22 leaves the dimension unchanged`, expected: highDimensions[i].score, actual: weightedBreakdown(changedCountry).dimensions[i].score });
  }
  checks.push(
    { name: 'PSG threshold: 49.999 is Needs Attention', expected: 'Needs Attention', actual: classify(49.999) },
    { name: 'PSG threshold: 50 is Developing', expected: 'Developing', actual: classify(50) },
    { name: 'PSG threshold: 74.999 is Developing', expected: 'Developing', actual: classify(74.999) },
    { name: 'PSG threshold: 75 is Strong', expected: 'Strong', actual: classify(75) },
  );
  let rejected = false;
  try { weightedBreakdown({}); } catch { rejected = true; }
  checks.push({ name: 'Incomplete answers are rejected', expected: true, actual: rejected });
  return checks.map(check => ({ ...check, passed: typeof check.expected === 'number' && typeof check.actual === 'number'
    ? Math.abs(check.expected - check.actual) < 1e-8 : check.expected === check.actual }));
}
